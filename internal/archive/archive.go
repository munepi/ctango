// Package archive inspects an upload archive before it is sent to CTAN, so
// that the most common rejections are caught locally.
package archive

import (
	"archive/tar"
	"archive/zip"
	"compress/gzip"
	"errors"
	"fmt"
	"io"
	"os"
	"path"
	"sort"
	"strings"
	"time"

	"github.com/munepi/ctango/internal/submit"
)

// Entry is a file or directory in the archive.
type Entry struct {
	Name  string // slash-separated, without leading "./"
	IsDir bool
	Size  int64
}

// List returns the entries of a .zip, .tgz or .tar.gz archive.
func List(file string) ([]Entry, error) {
	n := strings.ToLower(file)
	switch {
	case strings.HasSuffix(n, ".zip"):
		return listZip(file)
	case strings.HasSuffix(n, ".tgz"), strings.HasSuffix(n, ".tar.gz"):
		return listTarGz(file)
	}
	return nil, fmt.Errorf("%s: unknown archive type (expected .zip, .tgz or .tar.gz)", file)
}

func listZip(file string) ([]Entry, error) {
	r, err := zip.OpenReader(file)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", file, err)
	}
	defer r.Close()
	var out []Entry
	for _, f := range r.File {
		out = append(out, Entry{
			Name:  clean(f.Name),
			IsDir: f.FileInfo().IsDir(),
			Size:  int64(f.UncompressedSize64),
		})
	}
	return out, nil
}

func listTarGz(file string) ([]Entry, error) {
	f, err := os.Open(file)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", file, err)
	}
	defer gz.Close()
	tr := tar.NewReader(gz)
	var out []Entry
	for {
		h, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}
		switch h.Typeflag {
		case tar.TypeXGlobalHeader, tar.TypeXHeader:
			continue
		}
		out = append(out, Entry{
			Name:  clean(h.Name),
			IsDir: h.Typeflag == tar.TypeDir,
			Size:  h.Size,
		})
	}
	return out, nil
}

func clean(name string) string {
	name = strings.TrimPrefix(name, "./")
	return strings.TrimSuffix(name, "/")
}

// Files generated by TeX runs that CTAN rejects as "remainders".
var remainderSuffixes = []string{
	".aux", ".log", ".toc", ".out", ".lof", ".lot", ".bbl", ".blg",
	".idx", ".ind", ".ilg", ".glo", ".gls", ".hd", ".nav", ".snm",
	".vrb", ".fls", ".fdb_latexmk", ".synctex.gz", ".synctex",
	".bcf", ".run.xml", ".xdv", ".dvi",
}

// MaxAge is the age after which an archive is reported as possibly stale.
var MaxAge = 24 * time.Hour

// Inspect checks the archive for problems CTAN would complain about.
// pkg is the package name, used to check the top-level directory.
func Inspect(file, pkg string) ([]submit.Message, error) {
	var msgs []submit.Message
	errorf := func(format string, a ...any) {
		msgs = append(msgs, submit.Message{Severity: submit.SeverityError, Text: fmt.Sprintf(format, a...)})
	}
	warnf := func(format string, a ...any) {
		msgs = append(msgs, submit.Message{Severity: submit.SeverityWarning, Text: fmt.Sprintf(format, a...)})
	}

	st, err := os.Stat(file)
	if err != nil {
		return nil, err
	}
	if age := time.Since(st.ModTime()); age > MaxAge {
		warnf("archive %s was created %s ago; is it up to date?", path.Base(file), age.Round(time.Hour))
	}

	entries, err := List(file)
	if err != nil {
		return nil, err
	}
	if len(entries) == 0 {
		errorf("archive is empty")
		return msgs, nil
	}

	// Top-level layout: CTAN wants a single directory named after the package.
	tops := map[string]bool{}
	var looseFiles []string
	for _, e := range entries {
		first, _, nested := strings.Cut(e.Name, "/")
		if first == "" {
			continue
		}
		tops[first] = true
		if !nested && !e.IsDir {
			looseFiles = append(looseFiles, first)
		}
	}
	topDir := ""
	switch {
	case len(looseFiles) > 0:
		warnf("files at the top level of the archive (expected everything inside %s/): %s", pkg, strings.Join(looseFiles, ", "))
	case len(tops) != 1:
		warnf("archive has %d top-level directories; expected only %s/", len(tops), pkg)
	default:
		for t := range tops {
			topDir = t
		}
		if pkg != "" && topDir != pkg {
			warnf("top-level directory is %s/, expected %s/", topDir, pkg)
		}
	}

	var hasReadme, hasPDF bool
	var remainders, hidden []string
	for _, e := range entries {
		base := path.Base(e.Name)
		dir := path.Dir(e.Name)
		if !e.IsDir && (dir == topDir || (topDir == "" && dir == ".")) &&
			strings.HasPrefix(strings.ToLower(base), "readme") {
			hasReadme = true
		}
		if !e.IsDir && strings.HasSuffix(strings.ToLower(base), ".pdf") {
			hasPDF = true
		}
		if isHidden(e.Name) {
			hidden = append(hidden, e.Name)
			continue
		}
		if !e.IsDir && isRemainder(base) {
			remainders = append(remainders, e.Name)
		}
	}
	if !hasReadme {
		errorf("missing README in the top-level directory")
	}
	if !hasPDF {
		warnf("no PDF documentation found")
	}
	if len(remainders) > 0 {
		sort.Strings(remainders)
		errorf("generated files found (remove them from the archive): %s", strings.Join(remainders, ", "))
	}
	if len(hidden) > 0 {
		sort.Strings(hidden)
		warnf("hidden or system files found: %s", strings.Join(hidden, ", "))
	}
	return msgs, nil
}

func isRemainder(base string) bool {
	b := strings.ToLower(base)
	if strings.HasSuffix(b, "~") {
		return true
	}
	for _, s := range remainderSuffixes {
		if strings.HasSuffix(b, s) {
			return true
		}
	}
	return false
}

func isHidden(name string) bool {
	for _, c := range strings.Split(name, "/") {
		if strings.HasPrefix(c, ".") || c == "__MACOSX" || c == "Thumbs.db" {
			return true
		}
	}
	return false
}
